// Generates src/data/chat/blogFaq.js — every blog post's FAQ (question, answer, source URL) for the
// live help assistant, without shipping full article bodies in the chat bundle.
// Runs automatically before `npm run build`, `npm run dev` and `npm run build:preview-html`.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { BLOGS } = await import(pathToFileURL(path.join(root, 'src/data/blogs/index.js')).href);
const rows = [];
for (const b of BLOGS) {
  const mod = await import(pathToFileURL(path.join(root, `src/data/blogs/posts/${b.slug}.js`)).href);
  for (const f of mod.default.faqs || []) rows.push({ q: f.q, a: f.a, s: b.slug, t: b.title, c: b.category });
}
const out = `// AUTO-GENERATED by scripts/chat-kb.mjs from the blog posts — do not edit by hand.
// Each row: q = question, a = answer, s = blog slug (/blog/<s>), t = article title, c = category.
export const BLOG_FAQ = ${JSON.stringify(rows, null, 0).replace(/\},\{/g, '},\n  {')};
`;
writeFileSync(path.join(root, 'src/data/chat/blogFaq.js'), out);
console.log(`✔ Chat knowledge: ${rows.length} blog FAQ answers from ${BLOGS.length} posts`);
