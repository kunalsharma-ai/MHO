// Builds src/data/connectQr.generated.js: one compact QR matrix per URL in src/data/connect.js.
// Each code is stored as its side length plus the dark/light modules packed into base64 bits, so the
// Scan & Connect page can draw crisp, brand-coloured SVG codes without shipping a QR library.
// Usage: npm run qr:connect   (re-run whenever a URL in src/data/connect.js changes)
import QRCode from 'qrcode';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { ALL_QR_URLS } from '../src/data/connect.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = {};
for (const url of ALL_QR_URLS) {
  const { modules } = QRCode.create(url, { errorCorrectionLevel: 'M' });
  const n = modules.size;
  const bytes = Buffer.alloc(Math.ceil((n * n) / 8));
  for (let i = 0; i < n * n; i++) if (modules.data[i]) bytes[i >> 3] |= 128 >> (i & 7);
  out[url] = [n, bytes.toString('base64')];
}
const body = `// Generated by scripts/generate-connect-qr.mjs — do not edit. { url: [size, base64 bits] }\nexport default ${JSON.stringify(out, null, 1)};\n`;
await writeFile(path.join(root, 'src/data/connectQr.generated.js'), body);
console.log(`QR ${Object.keys(out).length} codes → src/data/connectQr.generated.js`);
