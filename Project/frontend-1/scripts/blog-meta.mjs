// Generates src/data/blogs/meta.js — a lightweight index (title, excerpt, category, read time…) of every post.
// Home, the blog list and the sitemap import this instead of the full ~220 KB article text, so the article
// bodies download only when someone opens a post. Runs automatically before `dev`, `build` and `build:preview`.
import { writeFile } from 'node:fs/promises';
import { BLOGS } from '../src/data/blogs/index.js';

const FIELDS = ['slug', 'title', 'excerpt', 'category', 'date', 'updated', 'readMins', 'trending', 'primaryKeyword'];
const rows = BLOGS.map((b) => Object.fromEntries(FIELDS.filter((k) => b[k] !== undefined).map((k) => [k, b[k]])));
const src = `// AUTO-GENERATED by scripts/blog-meta.mjs — do not edit by hand. Edit the posts in part*.js / extra-*.js.
const RAW = ${JSON.stringify(rows, null, 1)};

export const BLOG_META = RAW.map((b) => ({ ...b, cover: \`/images/blog/\${b.slug}.webp\` }));
export const BLOG_CATEGORIES = ['All', ...Array.from(new Set(BLOG_META.map((b) => b.category)))];
`;
await writeFile(new URL('../src/data/blogs/meta.js', import.meta.url), src);
console.log(`Blog index written: ${rows.length} posts`);
