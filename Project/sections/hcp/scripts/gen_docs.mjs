// Generates the alt-text inventory for every image in /public:
//   public/alt-text.json, docs/ALT_TEXT.md, docs/ALT_TEXT.csv
// Source of truth: src/data/altText.js (+ flag names from the country list).
//   node scripts/gen_docs.mjs [--dist]   (--dist also copies alt-text.json into dist/)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { ALT } = await import(pathToFileURL(path.join(ROOT, 'src/data/altText.js')));
const { LANGUAGES } = await import(pathToFileURL(path.join(ROOT, 'src/i18n/languages.js')));
const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/hcp.generated.json'), 'utf8'));

const countryName = Object.fromEntries(data.questions.country.options.map((o) => [o.v.toLowerCase(), o.l]));
const langByFlag = Object.fromEntries(LANGUAGES.map((l) => [l.flag, l]));
const PROFILE_NAMES = Object.fromEntries(data.profiles.map((p) => [p.slug, p.name]));

const rows = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(path.join(ROOT, 'public', dir), { withFileTypes: true })) {
    const rel = `${dir}/${e.name}`;
    if (e.isDirectory()) walk(rel);
    else if (/\.(svg|png|webp|ico)$/.test(e.name)) rows.push(rel);
  }
};
walk('images');
let regionEn = null; try { regionEn = new Intl.DisplayNames(['en'], { type: 'region' }); } catch { /* ignore */ }
rows.push('favicon.ico', 'apple-touch-icon.png');

const out = rows.sort().map((file) => {
  let alt = ALT[file];
  let usage = '';
  let decorative = false;
  const m = file.match(/^images\/flags\/([a-z]{2})\.svg$/);
  const w = file.match(/^images\/flags\/w\/([a-z]{2})\.webp$/);
  const st = file.match(/^images\/flags\/states\/([A-Z]{2})-([A-Z0-9]+)\.webp$/);
  if (w) {
    alt = `Flag of ${countryName[w[1]] || (regionEn && regionEn.of(w[1].toUpperCase())) || w[1].toUpperCase()}`;
    usage = 'Country lists, phone country picker';
    decorative = true;
  } else if (st) {
    alt = `Flag of the region ${st[1]}-${st[2]} (${(regionEn && regionEn.of(st[1])) || st[1]})`;
    usage = 'State / province list';
    decorative = true;
  } else if (file.startsWith('images/brand/')) {
    alt = file.includes('heart') ? 'MyHealthOpinions heart icon with a heartbeat line' : 'MyHealthOpinions logo — a red-to-orange heart with a heartbeat line beside the MyHealthOpinions wordmark';
    usage = 'Animated logo (header, Synapse core, pop-ups, completion badge, footer, e-mail)';
  } else if (file.includes('email/synapse')) {
    alt = 'Animated Synapse network: hexagon neurons light up one after another around the Evidence Core';
    usage = 'Reminder e-mail banner';
  } else if (m) {
    const c = m[1];
    const L = langByFlag[c];
    alt = `Flag of ${countryName[c] || c.toUpperCase()}`;
    usage = L ? `Language picker (${L.native}) + country lists` : 'Country lists';
    decorative = true; // always shown next to the visible country/language name → alt="" in the UI
  } else if (file.startsWith('images/email/')) {
    const slug = path.basename(file).replace(/\.(png|gif)$/, '');
    alt = `${PROFILE_NAMES[slug] || slug} icon`;
    usage = 'Reminder email profile card';
  } else if (file.startsWith('images/icon-') || file === 'favicon.ico' || file === 'apple-touch-icon.png') {
    alt = 'MyHealthOpinions heart icon';
    usage = 'Browser tab / home-screen icon (no alt rendered)';
  } else if (file.startsWith('images/profiles/')) usage = 'Profile card + review screen';
  else if (file.startsWith('images/hero/')) usage = 'Hero 3D floating object (decorative, aria-hidden)';
  else if (file.includes('mho-logo')) usage = 'Header + footer logo, emails';
  else if (file.includes('mho-heart')) usage = 'Hero orb centre (decorative)';
  else if (file.includes('og-image')) usage = 'Social share preview (Open Graph)';
  else if (file.includes('vault')) usage = 'Reward vault illustration';
  return { file, alt: alt || '', usage, decorative };
});

fs.writeFileSync(path.join(ROOT, 'public/alt-text.json'), JSON.stringify(out, null, 2));
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
const md = [
  '# Alt text inventory — MyHealthOpinions HCP portal',
  '',
  `Generated by \`scripts/gen_docs.mjs\` from \`src/data/altText.js\`. ${out.length} images.`,
  '',
  'Decorative images (hero floaters, flags shown next to a visible language name) are rendered with `alt=""`/`aria-hidden` in the UI so screen readers skip duplicates; their descriptive text is kept here for CMS/SEO use.',
  '',
  '| File | Alt text | Where it is used | Decorative in UI |',
  '|---|---|---|---|',
  ...out.map((r) => `| \`${r.file}\` | ${r.alt.replace(/\|/g, '/')} | ${r.usage} | ${r.decorative || /decorative/i.test(r.usage) ? 'yes' : 'no'} |`),
  '',
].join('\n');
fs.writeFileSync(path.join(ROOT, 'docs/ALT_TEXT.md'), md);
const csv = ['file,alt,usage,decorative', ...out.map((r) => [r.file, r.alt, r.usage, r.decorative].map((x) => `"${String(x).replace(/"/g, '""')}"`).join(','))].join('\n');
fs.writeFileSync(path.join(ROOT, 'docs/ALT_TEXT.csv'), csv);
if (process.argv.includes('--dist') && fs.existsSync(path.join(ROOT, 'dist'))) fs.copyFileSync(path.join(ROOT, 'public/alt-text.json'), path.join(ROOT, 'dist/alt-text.json'));
console.log(`✓ alt text for ${out.length} images → public/alt-text.json, docs/ALT_TEXT.md, docs/ALT_TEXT.csv`);
